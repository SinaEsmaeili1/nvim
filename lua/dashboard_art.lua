-- The arts that fit a screen `columns` wide, in `rows` rows shared with the
-- `menu_rows` rows of menu below the art.
function M.fitting(columns, rows, menu_rows)
  return vim.tbl_filter(function(art)
    if #art.lines + menu_rows > rows then
      return false
    end
    for _, line in ipairs(art.lines) do
      if vim.api.nvim_strwidth(line) > columns then
        return false
      end
    end
    return true
  end, M.arts)
end

-- A whole number from 1 to n. Lua's math.random isn't seeded when Neovim
-- starts, so it would pick the same art every time; libuv's random bytes aren't.
local function random_index(n)
  local a, b, c, d = vim.uv.random(4):byte(1, 4)
  return (((a * 256 + b) * 256 + c) * 256 + d) % n + 1
end

-- The lines of one art that fits, picked at random, or {} when none fits.
-- `random` (for tests) returns a whole number from 1 to the number it is given.
function M.pick(columns, rows, menu_rows, random)
  local fits = M.fitting(columns, rows, menu_rows)
  if #fits == 0 then
    return {}
  end
  return fits[(random or random_index)(#fits)].lines
end

return M
